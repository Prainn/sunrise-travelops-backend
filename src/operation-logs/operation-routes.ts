export function routeAction(controller: string, handler: string) {
  const [category, subject] = subjects[controller] ?? ['system', '系统接口'];
  const label = labels[handler] ?? handler;
  if (
    (controller === 'AccountLinksController' &&
      ['create', 'update', 'delete'].includes(handler)) ||
    (controller === 'AuthController' && handler === 'switchAccount')
  )
    return { category, label };
  return { category, label: (subject + ' / ' + label).slice(0, 80) };
}

export function writesOwnSuccess(controller: string, handler: string) {
  return (
    (controller === 'AuthController' && handler === 'switchAccount') ||
    (controller === 'AccountLinksController' &&
      ['create', 'update', 'delete'].includes(handler)) ||
    (controller === 'OperationLogsController' && handler === 'clientEvent')
  );
}

